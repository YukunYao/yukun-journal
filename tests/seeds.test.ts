import { describe, expect, it } from 'vitest'
import { addEntry, buySeedItem, emptyJournal, equipSeedItem, normalizeJournal, seedBalance, setWeightGoal, upsertWeight, weightRewardReason } from '../src/domain'
import { formatWeight } from '../src/presentation'

const day = new Date('2026-11-18T12:00:00')

describe('Light Seeds', () => {
  it('earns from distinct journal care and spends once', () => {
    const first = addEntry(emptyJournal(), { kind: 'meal', date: '2026-11-18', title: 'Lunch' }, day)
    const repeat = addEntry(first, { kind: 'meal', date: '2026-11-18', title: 'Dinner' }, day)
    expect(seedBalance(repeat)).toBe(10)
    const bought = buySeedItem(repeat, 'rose-scarf', day)
    expect(seedBalance(bought)).toBe(0)
    expect(equipSeedItem(bought, 'rose-scarf', 'outfit').equippedOutfit).toBe('rose-scarf')
    expect(() => buySeedItem(bought, 'rose-scarf', day)).toThrow('already yours')
    expect(() => buySeedItem(bought, 'blue-sleep-cap', day)).toThrow('Not enough')
    expect(() => equipSeedItem(repeat, 'blue-sleep-cap', 'outfit')).toThrow('Unlock')
  })

  it('rewards a new closest target record in either direction with a five-Seed daily cap', () => {
    let state = upsertWeight(emptyJournal(), { date: '2026-11-17', value: 70, unit: 'kg' }, day)
    state = setWeightGoal(state, 68, 'kg')
    state = upsertWeight(state, { date: '2026-11-18', value: 69.8, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(2)
    state = upsertWeight(state, { date: '2026-11-18', value: 69.5, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(5)
    const nextDay = new Date('2026-11-19T12:00:00')
    state = upsertWeight(state, { date: '2026-11-19', value: 69.2, unit: 'kg' }, nextDay)
    expect(seedBalance(state)).toBe(8)
    state = upsertWeight(state, { date: '2026-11-20', value: 69.9, unit: 'kg' }, new Date('2026-11-20T12:00:00'))
    expect(seedBalance(state)).toBe(8)
    let gain = upsertWeight(emptyJournal(), { date: '2026-11-17', value: 60, unit: 'kg' }, day)
    gain = setWeightGoal(gain, 62, 'kg')
    gain = upsertWeight(gain, { date: '2026-11-18', value: 60.1, unit: 'kg' }, day)
    expect(seedBalance(gain)).toBe(1)
  })

  it('catches up today’s goal progress when the target is set after the weigh-in', () => {
    let state = upsertWeight(emptyJournal(), { date: '2026-11-17', value: 70, unit: 'kg' }, day)
    state = upsertWeight(state, { date: '2026-11-18', value: 69.7, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(0)
    state = setWeightGoal(state, 68, 'kg', day)
    expect(seedBalance(state)).toBe(3)
    expect(state.weightSeedGrants[0].amount).toBe(3)
    expect(setWeightGoal(state, 67, 'kg', day).weightSeedGrants).toEqual(state.weightSeedGrants)
    expect(seedBalance(setWeightGoal(state, 67, 'kg', day))).toBe(3)
  })

  it('reconciles today’s weight Seeds when a mistaken weigh-in is replaced', () => {
    let state = upsertWeight(emptyJournal(), { date: '2026-11-17', value: 58, unit: 'kg' }, day)
    state = setWeightGoal(state, 56, 'kg', day)
    state = upsertWeight(state, { date: '2026-11-18', value: 57.7, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(3)
    state = upsertWeight(state, { date: '2026-11-18', value: 57.9, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(1)
    expect(state.weightSeedGrants[0].amount).toBe(1)
    state = upsertWeight(state, { date: '2026-11-18', value: 58, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(0)
    state = upsertWeight(state, { date: '2026-11-18', value: 57.8, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(2)
    expect(state.weightSeedGrants[0].amount).toBe(2)
  })

  it('keeps the five-Seed daily cap and a fully paid unlock after a correction', () => {
    let state = addEntry(emptyJournal(), { kind: 'meal', date: '2026-11-18', title: 'Lunch' }, day)
    state = upsertWeight(state, { date: '2026-11-17', value: 58, unit: 'kg' }, day)
    state = setWeightGoal(state, 56, 'kg', day)
    state = upsertWeight(state, { date: '2026-11-18', value: 57, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(15)
    state = buySeedItem(state, 'rose-scarf', day)
    state = upsertWeight(state, { date: '2026-11-18', value: 57.5, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(5)
    expect(state.seedUnlocks).toHaveLength(1)
    state = upsertWeight(state, { date: '2026-11-18', value: 58, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(0)
    expect(state.seedUnlocks).toHaveLength(1)
  })

  it('invalidates and unequips the newest unlock funded by corrected weight Seeds', () => {
    let state = addEntry(emptyJournal(), { kind: 'meal', date: '2026-11-18', title: 'Lunch' }, day)
    state = upsertWeight(state, { date: '2026-11-17', value: 58, unit: 'kg' }, day)
    state = setWeightGoal(state, 56, 'kg', day)
    state = upsertWeight(state, { date: '2026-11-18', value: 57.5, unit: 'kg' }, day)
    state = buySeedItem(state, 'felt-star-garland', day)
    state = equipSeedItem(state, 'felt-star-garland', 'decor')
    const beforeCorrection = state
    state = upsertWeight(state, { date: '2026-11-18', value: 58, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(10)
    expect(state.seedUnlocks).toHaveLength(0)
    expect(state.equippedDecor).toBeNull()
    expect(weightRewardReason(beforeCorrection, state, '2026-11-18', day)).toBe('corrected-down')
  })

  it('keeps a newly chosen target anchored to the corrected current weight', () => {
    let state = upsertWeight(emptyJournal(), { date: '2026-11-17', value: 58, unit: 'kg' }, day)
    state = setWeightGoal(state, 56, 'kg', day)
    state = upsertWeight(state, { date: '2026-11-18', value: 57.7, unit: 'kg' }, day)
    state = setWeightGoal(state, 55, 'kg', day)
    state = upsertWeight(state, { date: '2026-11-18', value: 57.9, unit: 'kg' }, day)
    expect(seedBalance(state)).toBe(1)
    expect(state.weightGoal?.targetKg).toBe(55)
    expect(state.weightGoal?.baselineKg).toBe(57.9)
    expect(state.weightGoal?.closestKg).toBe(57.9)
  })

  it('does not create goal rewards without a prior weigh-in or for historical dates', () => {
    const single = upsertWeight(emptyJournal(), { date: '2026-11-18', value: 69.7, unit: 'kg' }, day)
    expect(seedBalance(setWeightGoal(single, 68, 'kg', day))).toBe(0)
    let old = upsertWeight(emptyJournal(), { date: '2026-11-16', value: 70, unit: 'kg' }, day)
    old = upsertWeight(old, { date: '2026-11-17', value: 69.7, unit: 'kg' }, day)
    expect(seedBalance(setWeightGoal(old, 68, 'kg', day))).toBe(0)
  })

  it('caps late goal rewards at five and supports a higher target', () => {
    let state = upsertWeight(emptyJournal(), { date: '2026-11-17', value: 60, unit: 'kg' }, day)
    state = upsertWeight(state, { date: '2026-11-18', value: 60.9, unit: 'kg' }, day)
    state = setWeightGoal(state, 63, 'kg', day)
    expect(seedBalance(state)).toBe(5)
    expect(state.weightGoal?.baselineKg).toBe(60)
  })

  it('does not reward backfills and upgrades older local records', () => {
    const old = normalizeJournal({ entries: [], weights: [], seedLedger: [], spiritName: 'Pip' })
    expect(seedBalance(old)).toBe(0)
    expect(old.equippedOutfit).toBeNull()
    const transitional = normalizeJournal({ ...old, seedUnlocks: undefined, seedPurchases: [{ itemId: 'rose-scarf', cost: 10, unlockedAt: day.toISOString() }] } as unknown as typeof old)
    expect(transitional.seedUnlocks).toHaveLength(1)
    const record = upsertWeight(emptyJournal(), { date: '2026-11-17', value: 70, unit: 'kg' }, day)
    expect(seedBalance(record)).toBe(0)
  })

  it('keeps hundredths for weight records and user-set targets', () => {
    const state = upsertWeight(emptyJournal(), { date: '2026-11-18', value: 68.25, unit: 'kg' }, day)
    expect(state.weights[0].value).toBe(68.25)
    expect(formatWeight(state.weights[0].value, 'kg')).toBe('68.25 kg')
    expect(formatWeight(68, 'kg')).toBe('68.00 kg')
    expect(setWeightGoal(state, 65.75, 'kg').weightGoal?.targetKg).toBe(65.75)
    expect(() => upsertWeight(state, { date: '2026-11-18', value: 68.255, unit: 'kg' }, day)).toThrow('two decimal')
    expect(() => setWeightGoal(state, 65.755, 'kg')).toThrow('two decimal')
  })

  it('explains why a weight save did or did not earn seeds', () => {
    const empty = emptyJournal()
    const backfill = upsertWeight(empty, { date: '2026-11-17', value: 70, unit: 'kg' }, day)
    expect(weightRewardReason(empty, backfill, '2026-11-17', day)).toBe('past-date')
    const todayWithoutGoal = upsertWeight(empty, { date: '2026-11-18', value: 69, unit: 'kg' }, day)
    expect(weightRewardReason(empty, todayWithoutGoal, '2026-11-18', day)).toBe('no-goal')
    const goal = setWeightGoal(backfill, 68, 'kg')
    const noProgress = upsertWeight(goal, { date: '2026-11-18', value: 70, unit: 'kg' }, day)
    expect(weightRewardReason(goal, noProgress, '2026-11-18', day)).toBe('not-closer')
    const progress = upsertWeight(goal, { date: '2026-11-18', value: 69.8, unit: 'kg' }, day)
    expect(weightRewardReason(goal, progress, '2026-11-18', day)).toBe('earned')
    const sameDayUpdate = upsertWeight(progress, { date: '2026-11-18', value: 69.5, unit: 'kg' }, day)
    expect(weightRewardReason(progress, sameDayUpdate, '2026-11-18', day)).toBe('earned')
  })
})
